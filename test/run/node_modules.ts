// node_modules resolution: bare specifiers resolved by walking up to a
// node_modules dir, with package.json "main", index fallback, scoped
// packages, subpaths, a package requiring another package, .json require,
// and cache identity. The requiring module (./nm/main) lives inside nm/,
// so its bare requires walk up to nm/node_modules/. Deterministic.
const run = require("./nm/main");
console.log(run());

// a bare specifier with no matching package throws Cannot find module
function why(f) { try { f(); return "no throw"; } catch (e) { return e.constructor.name + ":" + e.message.includes("Cannot find module"); } }
console.log(why(() => require("definitely-not-installed")));
